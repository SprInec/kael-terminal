#!/usr/bin/env python3
"""Add Python-sized Yazi glyphs from a Yazi checkout's yazi-config/preset directory."""

import argparse
from pathlib import Path
import tomllib

from fontTools.colorLib.builder import LayerListBuilder
from fontTools.pens.recordingPen import DecomposingRecordingPen
from fontTools.pens.transformPen import TransformPen
from fontTools.pens.ttGlyphPen import TTGlyphPen
from fontTools.ttLib import TTFont
from fontTools.ttLib.tables.otTables import BaseGlyphPaintRecord, PaintFormat


ROOT = Path(__file__).resolve().parents[1]
PYTHON = 0xE606


def icon_aliases(preset):
    codepoints = set()
    for variant in ("dark", "light"):
        theme = tomllib.loads((preset / f"theme-{variant}.toml").read_text())
        codepoints.update(ord(rule["text"]) for rules in theme["icon"].values() for rule in rules)

    aliases = {}
    for codepoint in sorted(codepoints - {PYTHON}):
        # Reserve Plane 15 ranges separate from the existing Neovim aliases.
        if 0xE000 <= codepoint <= 0xF8FF:
            aliases[codepoint] = codepoint + 0xE4000
        elif 0xF0000 <= codepoint <= 0xF1FFF:
            aliases[codepoint] = codepoint + 0x4000
        else:
            raise ValueError(f"No Yazi font alias reserved for U+{codepoint:04X}")
    return aliases


def add_glyphs(font, nerd, aliases):
    cmap = font.getBestCmap()
    glyf = font["glyf"]
    reference = glyf[cmap[PYTHON]]
    advance = font["hmtx"][cmap[PYTHON]][0]
    width = reference.xMax - reference.xMin
    height = reference.yMax - reference.yMin
    center_x = (reference.xMin + reference.xMax) / 2
    center_y = (reference.yMin + reference.yMax) / 2
    colors = font["COLR"].table.BaseGlyphList
    paints = {record.BaseGlyph: record for record in colors.BaseGlyphPaintRecord}
    paint_builder = LayerListBuilder()
    nerd_cmap = nerd.getBestCmap()
    glyph_sets = {font: font.getGlyphSet(), nerd: nerd.getGlyphSet()}

    for codepoint, alias in aliases.items():
        source, original = (font, cmap[codepoint]) if codepoint in cmap else (nerd, nerd_cmap[codepoint])
        source_glyf = source["glyf"]
        glyph = source_glyf[original]
        scale = min(width / (glyph.xMax - glyph.xMin), height / (glyph.yMax - glyph.yMin))
        x = center_x - scale * (glyph.xMin + glyph.xMax) / 2
        y = center_y - scale * (glyph.yMin + glyph.yMax) / 2
        transform = (scale, 0, 0, scale, x, y)
        drawing = DecomposingRecordingPen(glyph_sets[source])
        glyph.draw(drawing, source_glyf)
        pen = TTGlyphPen(None)
        drawing.replay(TransformPen(pen, transform))
        fitted = pen.glyph()
        fitted.recalcBounds(glyf)

        name = f"u{alias:05X}"
        if alias in cmap and cmap[alias] != name:
            raise ValueError(f"Yazi alias U+{alias:05X} is already in use")
        if name not in glyf:
            glyf.glyphOrder.append(name)
        glyf[name] = fitted
        font["hmtx"][name] = (advance, fitted.xMin)
        for table in font["cmap"].tables:
            if table.isUnicode() and table.format == 12:
                table.cmap[alias] = name

        if source is font and original in paints:
            record = BaseGlyphPaintRecord()
            record.BaseGlyph = name
            record.Paint = paint_builder.buildPaint({
                "Format": PaintFormat.PaintTransform,
                "Paint": {"Format": PaintFormat.PaintColrGlyph, "Glyph": original},
                "Transform": dict(zip(("xx", "yx", "xy", "yy", "dx", "dy"), transform)),
            })
            paints[name] = record

    glyph_ids = font.getReverseGlyphMap(rebuild=True)
    colors.BaseGlyphPaintRecord = sorted(paints.values(), key=lambda record: glyph_ids[record.BaseGlyph])
    colors.BaseGlyphCount = len(paints)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("preset", type=Path)
    aliases = icon_aliases(parser.parse_args().preset)
    for style in ("Regular", "Bold"):
        path = ROOT / "fonts" / "StarshipPromptIcons" / f"StarshipPromptIcons-{style}.ttf"
        source = ROOT / "fonts" / "SauceCodeProNF" / f"SauceCodeProNerdFontMono-{style}.ttf"
        with TTFont(path, recalcTimestamp=False) as font, TTFont(source) as nerd:
            add_glyphs(font, nerd, aliases)
            font.save(path)

    target = ROOT / "config/yazi/plugins/kael-yazi-icons.yazi/main.lua"
    target.parent.mkdir(parents=True, exist_ok=True)
    lines = ["-- Generated by libexec/build-yazi-icons.py.", "return {"]
    lines.extend(f'  ["{chr(codepoint)}"] = "{chr(alias)}",' for codepoint, alias in aliases.items())
    target.write_text("\n".join([*lines, "}", ""]), encoding="utf-8")


if __name__ == "__main__":
    main()
